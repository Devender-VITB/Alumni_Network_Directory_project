export const getFilterOptions = () => {
  const departments = [...new Set(mockAlumni.map(a => a.department))].sort();
  const graduationYears = [...new Set(mockAlumni.map(a => a.graduationYear))].sort((a, b) => b - a);
  const industries = [...new Set(mockAlumni.map(a => a.industry))].sort();
  const degrees = [...new Set(mockAlumni.map(a => a.degree))].sort();
  const companies = [...new Set(mockAlumni.map(a => a.currentCompany))].sort();
  const countries = [...new Set(mockAlumni.map(a => a.country))].sort();
  
  const allSkills = mockAlumni.flatMap(a => a.skills);
  const skillCounts = allSkills.reduce((acc, s) => {
    acc[s] = (acc[s] || 0) + 1;
    return acc;
  }, {});
  const topSkills = Object.keys(skillCounts).sort((a, b) => skillCounts[b] - skillCounts[a]).slice(0, 15);

  return {
    departments,
    graduationYears,
    industries,
    degrees,
    companies,
    countries,
    skills: topSkills
  };
};
